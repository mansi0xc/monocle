import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createVerifyRequest, encodeVerifyRequest, decimalU64, MAX_BUNDLE_BYTES } from '../../../target/contracts-js/index.js';
const raw = await readFile(new URL('../../../fixtures/contracts/bundle.json', import.meta.url));
const request = createVerifyRequest('types-test', 'agave-98535e50-contracts-v1', raw, null);
assert.deepEqual(new TextEncoder().encode(request.bundle_json), new Uint8Array(raw));
const transported = JSON.parse(new TextDecoder().decode(encodeVerifyRequest(request)));
assert.equal(transported.bundle_json, request.bundle_json);
assert.equal(JSON.parse(transported.bundle_json).claim.slot, '18446744073709551615');
assert.equal(decimalU64(9007199254740993n), '9007199254740993');
assert.equal(decimalU64('18446744073709551615'), '18446744073709551615');
for (const value of [42, '01', '-1', '1e3', '18446744073709551616']) assert.throws(() => decimalU64(value));
const duplicate = '{"schema_version":1,"schema_version":2}';
assert.equal(createVerifyRequest('dup', 'x', new TextEncoder().encode(duplicate), null).bundle_json, duplicate);
assert.throws(() => createVerifyRequest('utf8', 'x', new Uint8Array([255]), null));
assert.throws(() => createVerifyRequest('size', 'x', new Uint8Array(MAX_BUNDLE_BYTES + 1), null));
const bom = new Uint8Array([239, 187, 191, 123, 125]);
assert.deepEqual(new TextEncoder().encode(createVerifyRequest('bom', 'x', bom, null).bundle_json), bom);
console.log('TypeScript boundary checks passed: exact integers, raw byte preservation, duplicate retention, UTF-8 and size checks.');
