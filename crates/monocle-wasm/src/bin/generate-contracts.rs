//! Prints `packages/contracts/src/generated.ts`: every enumerated value and
//! constant the browser shares with Rust. The gate regenerates and compares it.
use monocle_core::{
    AGAVE_REVISION, CheckStatus, Code, Conclusion, MAX_BUNDLE_BYTES, MAX_CERTIFICATES,
    MAX_CHECKPOINT_BYTES, MAX_MUTATIONS, MAX_REQUEST_BYTES, MAX_VALIDATORS, PROFILE_ID, SourceKind,
    Stage, capture, certificate, experiment, finality,
};
use monocle_wasm::{ABI_VERSION, MAX_INPUT_BYTES, Operation};
use serde::Serialize;
use std::fmt::Write;

fn names<T: Serialize>(values: &[T]) -> String {
    let quoted: Vec<String> = values
        .iter()
        .map(|value| serde_json::to_string(value).expect("enum names serialize"))
        .collect();
    format!("[\n  {},\n]", quoted.join(",\n  "))
}

fn main() {
    let mut out = String::from(
        "// Generated by `cargo run -p monocle-wasm --bin generate-contracts`. Do not edit.\n\
         // Rust is the source of truth; the gate fails if this file is stale.\n",
    );
    let lists: [(&str, &str, String); 10] = [
        ("DIAGNOSTIC_CODES", "DiagnosticCode", names(Code::ALL)),
        ("STAGES", "Stage", names(Stage::ALL)),
        ("CHECK_STATUSES", "CheckStatus", names(CheckStatus::ALL)),
        ("CONCLUSIONS", "Conclusion", names(Conclusion::ALL)),
        ("SOURCE_KINDS", "SourceKind", names(SourceKind::ALL)),
        (
            "CERTIFICATE_KINDS",
            "CertificateKind",
            names(certificate::CertificateKind::ALL),
        ),
        ("CLAIM_KINDS", "ClaimKind", names(finality::ClaimKind::ALL)),
        (
            "EVIDENCE_SCOPES",
            "EvidenceScope",
            names(finality::EvidenceScope::ALL),
        ),
        (
            "FINALITY_PATHS",
            "FinalityPath",
            names(finality::FinalityPath::ALL),
        ),
        (
            "CAPTURE_OBSERVATIONS",
            "CaptureObservation",
            names(capture::CaptureObservation::ALL),
        ),
    ];
    for (constant, alias, values) in lists {
        write!(
            out,
            "\nexport const {constant} = {values} as const;\nexport type {alias} = (typeof {constant})[number];\n"
        )
        .unwrap();
    }
    out.push('\n');
    for (name, value) in [
        ("MAX_BUNDLE_BYTES", MAX_BUNDLE_BYTES),
        ("MAX_CHECKPOINT_BYTES", MAX_CHECKPOINT_BYTES),
        ("MAX_REQUEST_BYTES", MAX_REQUEST_BYTES),
        ("MAX_CERTIFICATES", MAX_CERTIFICATES),
        ("MAX_VALIDATORS", MAX_VALIDATORS),
        ("MAX_MUTATIONS", MAX_MUTATIONS),
        ("MAX_REPLAY_BYTES", experiment::MAX_REPLAY_BYTES),
        ("MAX_CAPTURE_BYTES", capture::MAX_CAPTURE_BYTES),
        ("MAX_BRIDGE_INPUT_BYTES", MAX_INPUT_BYTES),
    ] {
        writeln!(out, "export const {name} = {value};").unwrap();
    }
    out.push('\n');
    for (name, value) in [
        ("CONTRACTS_PROFILE_ID", PROFILE_ID),
        ("BASE2_PROFILE_ID", certificate::PROFILE_ID),
        ("CERTIFICATE_WIRE_FORMAT", certificate::WIRE_FORMAT),
        ("FINALITY_POLICY_ID", finality::POLICY_ID),
        ("REPLAY_FORMAT", experiment::REPLAY_FORMAT),
        ("CAPTURE_ADAPTER_ID", capture::ADAPTER_ID),
        ("AGAVE_REVISION", AGAVE_REVISION),
    ] {
        let quoted = serde_json::to_string(value).expect("strings serialize");
        writeln!(out, "export const {name} = {quoted};").unwrap();
    }
    writeln!(out, "\nexport const ABI_VERSION = {ABI_VERSION};").unwrap();
    out.push_str(
        "\n/** WASM bridge operation numbers (stable ABI). */\nexport const Operation = {\n",
    );
    for op in Operation::ALL {
        writeln!(out, "  {op:?}: {},", op as u32).unwrap();
    }
    out.push_str(
        "} as const;\nexport type Operation = (typeof Operation)[keyof typeof Operation];\n",
    );
    print!("{out}");
}
